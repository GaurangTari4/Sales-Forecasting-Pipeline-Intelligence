"""Executable temporal-integrity assertions for persisted feature datasets."""
from __future__ import annotations

from datetime import datetime

from .builder import build_feature_dataset
from .contracts import FEATURE_COLUMNS, FeatureConfig


class FeatureLeakageError(ValueError):
    """Raised when persisted features contain information unavailable at their cutoff."""


PROTECTED_NAMES = {"ground_truth", "ground_truth_outcomes", "ground_truth_anomalies", "issue_id", "issue_type", "final_outcome", "latent_quality", "booking_amount", "realized_booking_reporting"}


def assert_temporal_integrity(dataset: dict[str, list[dict]], rows: list[dict], config: FeatureConfig = FeatureConfig()) -> None:
    """Verify the persisted projection equals a fresh as-of reconstruction.

    This detects future stage/activity/change/booking-derived values, future-derived
    aggregate statistics, overwritten current-state fields, and protected truth columns.
    The labels are intentionally absent: targets must be generated by ``build_labels``.
    """
    for row in rows:
        forbidden = PROTECTED_NAMES & set(row)
        if forbidden:
            raise FeatureLeakageError(f"protected columns in features for {row.get('opportunity_id')}: {sorted(forbidden)}")
        unknown = set(row) - set(FEATURE_COLUMNS)
        if unknown:
            raise FeatureLeakageError(f"unversioned feature columns: {sorted(unknown)}")
    expected = build_feature_dataset(dataset, config)
    if rows != expected:
        raise FeatureLeakageError(
            "Persisted feature rows do not equal a fresh snapshot-cutoff reconstruction; "
            "a future event, future booking/conversion statistic, or overwritten state may have entered the matrix."
        )
